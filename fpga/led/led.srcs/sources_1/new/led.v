
module led(                     
    input     key , //输入按键
    
    output    led   //输出LED灯
);

//*****************************************************
//**                  main code
//*****************************************************

//上电按键默认高电平，LED灯保持常灭
//按键被按下，按键值为低电平，LED灯被点亮
assign led = ~key;    //将按键的值取反后赋值给LED灯

endmodule